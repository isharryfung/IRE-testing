-- 3) Example queries: candidate generation (blocking), similarity, create match candidate rows
-- A) Exact-match blocking by email
SELECT sr.source_record_id, gr.golden_id, 'email' as block_on
FROM source_records sr
JOIN golden_records gr ON LOWER(sr.normalized_email) = LOWER(gr.canonical_email)
WHERE sr.normalized_email IS NOT NULL;

-- B) Exact-match blocking by phone (norm stripping non-digit characters expected at ingest)
SELECT sr.source_record_id, gr.golden_id, 'phone' as block_on
FROM source_records sr
JOIN golden_records gr ON REGEXP_REPLACE(sr.normalized_phone,'\D') = REGEXP_REPLACE(gr.canonical_phone,'\D')
WHERE sr.normalized_phone IS NOT NULL;

-- C) Name similarity (using UTL_MATCH EDIT_DISTANCE_SIMILARITY which returns 0-100)
SELECT sr.source_record_id, gr.golden_id,
       UTL_MATCH.EDIT_DISTANCE_SIMILARITY(sr.normalized_name, gr.canonical_name)/100 AS name_sim
FROM source_records sr
CROSS JOIN golden_records gr
WHERE sr.normalized_name IS NOT NULL
  AND UTL_MATCH.EDIT_DISTANCE_SIMILARITY(sr.normalized_name, gr.canonical_name) >= 70; -- threshold 70%

-- D) Assemble candidate scores (example with weights applied in query)
-- Suppose priorities: name=40, email=80, phone=60, id=100 (only present fields considered)
-- For demo, compute dynamic weights per row using DECODE to check present fields
SELECT
  sr.source_record_id,
  gr.golden_id,
  CASE WHEN sr.normalized_name IS NOT NULL THEN UTL_MATCH.EDIT_DISTANCE_SIMILARITY(sr.normalized_name, gr.canonical_name)/100 ELSE NULL END AS sim_name,
  CASE WHEN sr.normalized_email IS NOT NULL THEN CASE WHEN LOWER(sr.normalized_email)=LOWER(gr.canonical_email) THEN 1 ELSE 0 END ELSE NULL END AS sim_email,
  CASE WHEN sr.normalized_phone IS NOT NULL THEN CASE WHEN REGEXP_REPLACE(sr.normalized_phone,'\D')=REGEXP_REPLACE(gr.canonical_phone,'\D') THEN 1 ELSE 0 END ELSE NULL END AS sim_phone,
  -- dynamic weights calculation (simplified) 
  -- present_priority_sum = sum of priorities for non-null fields
  -- weight_name = 40/present_priority_sum etc.
  40/( (CASE WHEN sr.normalized_name IS NOT NULL THEN 40 ELSE 0 END) + (CASE WHEN sr.normalized_email IS NOT NULL THEN 80 ELSE 0 END) + (CASE WHEN sr.normalized_phone IS NOT NULL THEN 60 ELSE 0 END) + (CASE WHEN sr.hkid IS NOT NULL THEN 100 ELSE 0 END) ) AS weight_name,
  80/( (CASE WHEN sr.normalized_name IS NOT NULL THEN 40 ELSE 0 END) + (CASE WHEN sr.normalized_email IS NOT NULL THEN 80 ELSE 0 END) + (CASE WHEN sr.normalized_phone IS NOT NULL THEN 60 ELSE 0 END) + (CASE WHEN sr.hkid IS NOT NULL THEN 100 ELSE 0 END) ) AS weight_email,
  60/( (CASE WHEN sr.normalized_name IS NOT NULL THEN 40 ELSE 0 END) + (CASE WHEN sr.normalized_email IS NOT NULL THEN 80 ELSE 0 END) + (CASE WHEN sr.normalized_phone IS NOT NULL THEN 60 ELSE 0 END) + (CASE WHEN sr.hkid IS NOT NULL THEN 100 ELSE 0 END) ) AS weight_phone
FROM source_records sr
CROSS JOIN golden_records gr
WHERE sr.source_record_id = :IN_SRC_REC_ID; -- bind param for incoming source_record_id

