-- Oracle schema for Identity Resolution Engine (IRE)
-- Creates source_records, golden_records, record_links, manual_review_queue, merge_history
-- Use a dedicated schema/user for IRE (recommended).

-- 1) Create tables
CREATE TABLE source_records (
  source_record_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_name        VARCHAR2(100) NOT NULL, -- e.g., HR, SIS, CRM, ThirdParty
  source_pk          VARCHAR2(200) NOT NULL, -- original primary key in source
  raw_payload        CLOB,                    -- raw JSON payload
  normalized_name    VARCHAR2(4000),
  normalized_email   VARCHAR2(320),
  normalized_phone   VARCHAR2(50),
  hkid               VARCHAR2(50),
  emplid             VARCHAR2(50),
  studentid          VARCHAR2(50),
  alumniid           VARCHAR2(50),
  address            VARCHAR2(2000),
  ingest_ts          TIMESTAMP DEFAULT SYSTIMESTAMP,
  ingest_user        VARCHAR2(100)
);

CREATE TABLE golden_records (
  golden_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  canonical_name     VARCHAR2(4000),
  canonical_email    VARCHAR2(320),
  canonical_phone    VARCHAR2(50),
  canonical_hkid     VARCHAR2(50),
  canonical_emplid   VARCHAR2(50),
  canonical_studentid VARCHAR2(50),
  canonical_alumniid VARCHAR2(50),
  canonical_address  VARCHAR2(2000),
  provenance         CLOB, -- JSON describing field-level provenance
  last_updated       TIMESTAMP DEFAULT SYSTIMESTAMP,
  status             VARCHAR2(50) DEFAULT 'active'
);

CREATE TABLE record_links (
  link_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_record_id   NUMBER NOT NULL,
  golden_id          NUMBER NOT NULL,
  link_confidence    NUMBER(5,4) NOT NULL, -- 0.0000 - 1.0000
  link_method        VARCHAR2(50), -- 'deterministic'|'probabilistic'|'manual'
  evidence           CLOB,
  link_ts            TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT fk_rl_src_rec FOREIGN KEY (source_record_id) REFERENCES source_records(source_record_id),
  CONSTRAINT fk_rl_golden FOREIGN KEY (golden_id) REFERENCES golden_records(golden_id)
);

CREATE TABLE manual_review_queue (
  task_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_record_id   NUMBER NOT NULL,
  candidate_goldens  VARCHAR2(2000), -- comma-separated golden_ids OR JSON list
  best_confidence    NUMBER(5,4),
  status             VARCHAR2(50) DEFAULT 'open', -- open|assigned|resolved
  assigned_to        VARCHAR2(100),
  created_ts         TIMESTAMP DEFAULT SYSTIMESTAMP,
  resolved_ts        TIMESTAMP,
  reviewer_decision  VARCHAR2(50),
  notes              CLOB,
  CONSTRAINT fk_mrq_src_rec FOREIGN KEY (source_record_id) REFERENCES source_records(source_record_id)
);

CREATE TABLE merge_history (
  event_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type         VARCHAR2(50), -- 'merge'|'split'|'update'|'link'
  actor              VARCHAR2(100), -- 'system' or reviewer name/id
  details            CLOB,
  event_ts           TIMESTAMP DEFAULT SYSTIMESTAMP
);

